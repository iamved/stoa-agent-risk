import type { ReactNode } from "react";
import { FRAMEWORKS, useApp } from "../app/context";
import { buildHash, type ScreenId } from "../app/router";
import { activeFindings, formatDate } from "../data/selectors";
import { printAs } from "../app/print";
import { PrintSummary } from "./PrintSummary";

const NAV: { id: ScreenId; label: string }[] = [
  { id: "overview", label: "Overview" },
  { id: "inventory", label: "AI inventory" },
  { id: "findings", label: "Findings" },
  { id: "drift", label: "Drift" },
  { id: "register", label: "Risk register" },
  { id: "evidence", label: "Evidence" },
];

function Wordmark() {
  return (
    <a href={buildHash("overview")} className="flex items-center gap-2 text-white no-underline">
      <svg width="26" height="26" viewBox="0 0 32 32" aria-hidden="true">
        <rect width="32" height="32" rx="6" fill="var(--color-gold)" />
        <path d="M9 22V10h14M9 16h10" stroke="var(--color-navy)" strokeWidth="3" fill="none" strokeLinecap="round" />
      </svg>
      <span className="font-serif text-[20px] tracking-wide">Stoa</span>
    </a>
  );
}

export function Shell({ screen, children }: { screen: ScreenId; children: ReactNode }) {
  const { envelope, framework, setFramework } = useApp();
  const r = envelope.registry;
  const counts: Partial<Record<ScreenId, number>> = {
    inventory: r.agents.length,
    findings: activeFindings(r).length,
    drift: envelope.diff ? envelope.diff.summary.agents_changed + envelope.diff.summary.agents_added + envelope.diff.summary.agents_removed : undefined,
    register: envelope.register.length,
  };
  const head = r.repository.head_commit;

  return (
    <div className="min-h-screen flex flex-col md:flex-row">
      <nav aria-label="Screens" className="no-print bg-navy text-white md:w-[220px] md:min-h-screen md:sticky md:top-0 md:self-start flex md:flex-col">
        <div className="px-4 py-4 border-b border-white/10 hidden md:block">
          <Wordmark />
        </div>
        <ul className="m-0 p-2 list-none flex md:flex-col gap-1 overflow-x-auto w-full">
          {NAV.map((item) => {
            const active = item.id === screen;
            return (
              <li key={item.id}>
                <a
                  href={buildHash(item.id)}
                  aria-current={active ? "page" : undefined}
                  className={`flex items-center justify-between gap-2 rounded px-3 py-2 text-[13.5px] no-underline whitespace-nowrap ${active ? "bg-white/10 text-gold border-l-2 border-gold" : "text-white/85 hover:bg-white/5 hover:text-white"}`}
                >
                  <span>{item.label}</span>
                  {counts[item.id] !== undefined ? <span className="text-[11px] text-white/60 tabular-nums">{counts[item.id]}</span> : null}
                </a>
              </li>
            );
          })}
        </ul>
        <div className="mt-auto px-4 py-3 text-[11px] text-white/50 hidden md:block">Generated by Stoa {envelope.generator.version}</div>
      </nav>

      <div className="flex-1 min-w-0">
        <header className="bg-panel border-b border-line px-5 py-3 flex flex-wrap items-center gap-x-5 gap-y-2">
          <div className="md:hidden">
            <Wordmark />
          </div>
          <div className="min-w-0">
            <div className="font-serif text-[18px] text-navy leading-tight truncate">{r.repository.name}</div>
            <div className="caption">
              {r.repository.git_ref ? <span className="mono">{r.repository.git_ref}</span> : "no git ref"}
              {" · "}
              {head ? `committed ${formatDate(head.date)}` : "commit date unavailable"}
              {" · "}
              {r.summary.files_scanned} files scanned
            </div>
          </div>
          <div className="ml-auto flex items-center gap-3 no-print">
            <label className="caption flex items-center gap-2">
              Framework
              <select value={framework} onChange={(e) => setFramework(e.target.value as typeof framework)} className="rounded border border-line bg-panel px-2 py-1 text-[13px] text-ink" aria-label="Framework used for labels">
                {FRAMEWORKS.map((f) => (
                  <option key={f.id} value={f.id}>
                    {f.label}
                  </option>
                ))}
              </select>
            </label>
            <button type="button" onClick={() => printAs("summary")} className="rounded border border-navy bg-navy text-white px-3 py-1.5 text-[13px] hover:bg-navy-700">
              Print summary
            </button>
          </div>
        </header>
        <main className="px-5 py-5 max-w-[1400px]">
          <div className="screen-content">{children}</div>
          <PrintSummary />
        </main>
      </div>
    </div>
  );
}
